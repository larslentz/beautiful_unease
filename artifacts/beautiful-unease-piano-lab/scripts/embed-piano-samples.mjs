import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sampleDirectory = path.join(
  projectRoot,
  "node_modules",
  "@audio-samples",
  "piano-mp3-velocity8",
  "audio",
);
const sampleFiles = (await readdir(sampleDirectory))
  .filter((file) => /^[A-G]#?[0-8]v8\.mp3$/.test(file))
  .map((file) => {
    const match = file.match(/^([A-G])(#?)([0-8])v8\.mp3$/);
    const pitchClasses = { C: 0, D: 2, E: 4, F: 5, G: 7, A: 9, B: 11 };
    const midi = (Number(match[3]) + 1) * 12 + pitchClasses[match[1]] + (match[2] ? 1 : 0);
    return { file, midi };
  })
  .sort((a, b) => a.midi - b.midi);

if (sampleFiles.length !== 30) {
  throw new Error(`Expected 30 Salamander piano samples; found ${sampleFiles.length}.`);
}

const encodedSamples = await Promise.all(
  sampleFiles.map(async ({ file, midi }) => {
    const bytes = await readFile(path.join(sampleDirectory, file));
    return `  ${midi}: "${bytes.toString("base64")}"`;
  }),
);
const output = [
  "// Generated by scripts/embed-piano-samples.mjs from Salamander Grand Piano V3.",
  "// Samples by Alexander Holm; CC BY 3.0. See AUDIO-SAMPLES-LICENSE.txt.",
  "window.PIANO_SAMPLE_DATA = Object.freeze({",
  `${encodedSamples.join(",\n")}`,
  "});",
  "",
].join("\n");

await writeFile(path.join(projectRoot, "piano-samples.js"), output);
console.log(`Embedded ${sampleFiles.length} piano samples (${Buffer.byteLength(output)} bytes).`);
